#pragma once

#include "wasm4.h"

using u8 = uint8_t;
using u32 = uint32_t;
using usize = size_t;

using i32 = int32_t;

struct Sprite {
    const u8 *data;
    const u8 bpp;

    void draw(i32 x, i32 y, u32 flags) const {
        blit(
            data,
            x, y,
            8, 8,
            flags | bpp
        );
    }
    
    template<usize N>
    constexpr Sprite(u8 (&data)[N]) :
        data(data),
        bpp((N / 8) - 1)
    { }
};

